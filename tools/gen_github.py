"""Throwaway generator: projection.toml + GitHub's spec -> Rust. A real build would be a
proc macro or build step. Fails if a declared path does not exist in the spec."""
import json, sys, tomllib

spec = json.load(open(sys.argv[1]))
projection = tomllib.load(open(sys.argv[2], "rb"))
hooks = spec["x-webhooks"]

def res(s):
    while isinstance(s, dict) and "$ref" in s:
        n = spec
        for x in s["$ref"].lstrip("#/").split("/"):
            n = n[x]
        s = n
    return s

def variants(s):
    s = res(s)
    out = [s]
    for k in ("allOf", "anyOf", "oneOf"):
        for sub in s.get(k, []) or []:
            out += variants(sub)
    return out

def find(root, path):
    cur = [root]
    for part in path.split("."):
        nxt = []
        for s in cur:
            for v in variants(s):
                p = (v.get("properties") or {}).get(part)
                if p is not None:
                    nxt.append(p)
        if not nxt:
            sys.exit(f"error: `{path}` is not in the spec (no `{part}`)")
        cur = nxt
    leaves = [v for s in cur for v in variants(s) if v.get("type") or "enum" in v]
    return leaves[0]

def camel(s):
    return "".join(p.capitalize() for p in s.replace("-", "_").split("_"))

out = ["// @generated by tools/gen_github.py. Do not edit.", "use almanac::prelude::*;", ""]
for name, decl in projection.items():
    root = hooks[decl["webhook"]]["post"]["requestBody"]["content"]["application/json"]["schema"]
    kind = decl["kind"]
    fields, inits, enums = [], [], []
    for fname, f in decl["fields"].items():
        s = find(root, f["path"])
        ptr = "/" + f["path"].replace(".", "/")
        t = s.get("type")
        nullable = s.get("nullable") or (isinstance(t, list) and "null" in t)
        if "as" in f:
            if t != "string":
                sys.exit(f"error: `{f['path']}` is {t}, cannot be `as {f['as']}`")
            ty, init = f["as"], f'p.field("{ptr}")?'
        elif "enum" in s:
            ty = name + camel(fname)
            vs = "".join(f'        #[serde(rename = "{e}")] {camel(e)},\n' for e in s["enum"] if e is not None)
            enums.append(f"clean! {{\n    pub enum {ty} {{\n{vs}        #[serde(other)] Unknown,\n    }}\n}}\n")
            init = f'p.field("{ptr}")?'
        elif t == "integer":
            ty, init = "u64", f'p.field("{ptr}")?'
        elif t == "boolean":
            ty, init = "bool", f'p.field("{ptr}")?'
        elif nullable:
            ty, init = "Untrusted<Option<String>>", f'p.optional_text("{ptr}")?'
        else:
            ty, init = "Untrusted<String>", f'p.text("{ptr}")?'
        fields.append(f"        pub {fname}: {ty},")
        inits.append(f"            {fname}: {init},")
    out += enums
    out.append(f"observed! {{\n    pub struct {name} {{\n" + "\n".join(fields) + "\n    }\n}\n")
    out.append(f'impl Event for {name} {{\n    const KIND: &\'static str = "{kind}";\n    fn parse(p: &Payload<\'_>) -> Result<Self, Malformed> {{\n        Ok(Self {{\n' + "\n".join(inits) + "\n        })\n    }\n}\n")
print("\n".join(out))
